TRANSCRIPT_ROLE_REVIEW_SYSTEM_PROMPT = """Ты второй проверяющий разметки телефонного
разговора автосервиса. Исправь только границы реплик и speaker, если первичная разметка
сомнительна. Текст должен быть полностью lossless относительно исходного STT:
ни одного нового, удалённого, заменённого или переставленного слова. Метаданные звонка
используй лишь как слабый контекст. Не чередуй роли автоматически. Если роль действительно
неясна — unknown. Верни только JSON по заданной схеме.
"""


def _metadata_block(context: dict[str, Any] | None) -> str:
    if not context:
        return "metadata: отсутствуют"
    keys = (
        "direction",
        "client_number",
        "employee_extension",
        "employee_name",
        "from_number",
        "to_number",
    )
    lines = [f"{key}: {context.get(key) or '-'}" for key in keys]
    return "metadata:\n" + "\n".join(lines)


def build_transcript_role_prompt(
    transcript: str, context: dict[str, Any] | None = None
) -> str:

    return (
        "Раздели STT-текст на реплики и назначь роли без изменения слов.\n\n"
        f"{_metadata_block(context)}\n\n"
        f"<transcript>\n{transcript}\n</transcript>"
    )


def build_transcript_role_review_prompt(
    transcript: str,
    initial_turns: list[dict[str, Any]] | None,
    context: dict[str, Any] | None = None,
) -> str:
    return (
        "Проверь первичную разметку. Особое внимание: unknown, слишком крупные реплики, "
        "неверная роль сотрудника/клиента и механическое чередование. Не изменяй слова.\n\n"
        f"{_metadata_block(context)}\n\n"
        f"<source_transcript>\n{transcript}\n</source_transcript>\n\n"
        f"<initial_turns>\n{initial_turns or []}\n</initial_turns>"
    )
